// Extension → VS Code language id, from VS Code's built-in languages, for a theme's `languageIds`.
export const languageOfExtension: Readonly<Record<string, string>> = Object.fromEntries(
  Object.entries(byLanguage).flatMap(([language, extensions]) =>
    extensions.map((extension) => [extension, language]),
  ),
)
